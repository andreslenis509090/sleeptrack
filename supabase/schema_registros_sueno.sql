-- =============================================================================
-- 2. Tabla de Registros de Sueño (registros_sueno)
-- RF03: Registro diario de hora de acostarse, despertar, fecha y calificación.
-- RF04: Almacena duracion_horas calculada automáticamente cruzando medianoche.
-- RF05 / RN02: Hora de inicio no futura contra reloj en tiempo real.
-- RF06: Tipos de datos estrictos y calificación en escala 1 a 5.
-- RF08 / RN01: Restricción única usuario+fecha para evitar duplicados diarios.
-- RF09: Permite eliminar registros propios.
-- RF10: ON DELETE CASCADE cuando se elimina el usuario propietario.
-- RNF04: Persistencia relacional en la nube garantizada sin almacenamiento local.
-- =============================================================================
CREATE TABLE IF NOT EXISTS registros_sueno (
    id_registro BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    fecha DATE NOT NULL,
    hora_acostarse TIME WITHOUT TIME ZONE NOT NULL,
    hora_despertar TIME WITHOUT TIME ZONE NOT NULL,
    calificacion SMALLINT NOT NULL CHECK (calificacion >= 1 AND calificacion <= 5),
    duracion_horas NUMERIC(4, 2) NOT NULL CHECK (duracion_horas >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),

    -- =========================================================================
    -- REGLA DE NEGOCIO RN01:
    -- "Solo se permite un registro de sueño por usuario por fecha." (RF08)
    -- =========================================================================
    CONSTRAINT uq_registros_sueno_usuario_fecha UNIQUE (id_usuario, fecha)
);

-- =============================================================================
-- 3. Índices de Rendimiento (RNF08)
-- Optimización para consultas frecuentes por usuario y orden cronológico (HU2, RF11-RF13).
-- =============================================================================
CREATE INDEX IF NOT EXISTS idx_registros_sueno_usuario_fecha 
    ON registros_sueno(id_usuario, fecha DESC);

CREATE INDEX IF NOT EXISTS idx_registros_sueno_fecha 
    ON registros_sueno(fecha);

-- =============================================================================
-- 4. Trigger para Actualización Automática de updated_at
-- =============================================================================
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_registros_sueno_updated_at ON registros_sueno;
CREATE TRIGGER trg_registros_sueno_updated_at
    BEFORE UPDATE ON registros_sueno
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

-- =============================================================================
-- 5. Seguridad a Nivel de Filas (Row Level Security - RLS)
-- Habilita RLS y define políticas de acceso para el cliente del backend.
-- =============================================================================
ALTER TABLE registros_sueno ENABLE ROW LEVEL SECURITY;

-- Política de acceso total para operaciones realizadas por el backend
DROP POLICY IF EXISTS "Permitir acceso completo a registros_sueno" ON registros_sueno;
CREATE POLICY "Permitir acceso completo a registros_sueno"
    ON registros_sueno
    FOR ALL
    USING (true)
    WITH CHECK (true);

-- Política para la tabla usuarios
ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir acceso completo a usuarios" ON usuarios;
CREATE POLICY "Permitir acceso completo a usuarios"
    ON usuarios
    FOR ALL
    USING (true)
    WITH CHECK (true);

