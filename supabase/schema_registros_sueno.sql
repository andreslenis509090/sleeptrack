-- Habilitar extensión para UUIDs si se requiere a futuro
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- =============================================================================
-- 1. Tabla de Usuarios
-- Prerrequisito para la integridad referencial y clave foránea (RNF04, RF01, RF10).
-- Cumple con el Diagrama de Dominio del Informe #3:
-- Usuario "1" *-- "0..*" RegistroSueno : posee / composicion (eliminación en cascada RF10)
-- =============================================================================
CREATE TABLE IF NOT EXISTS usuarios (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    ocupacion VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    meta_sueno NUMERIC(4, 2) DEFAULT 8.0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

